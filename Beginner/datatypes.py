# data types describes kind of value a variable holds.
# python is dynamically typed language meaning you do not specify a variables data type when you create it.
# here are the 4main data types you will interact with.

# 1. Integer - is a whole number without a decimal.

my_integer_var = 20 #integer

print("Integer:", my_integer_var)   # Integer: 20

# 2. Float - number with a decimal point.

my_float_var = 9.12

print("Float:", my_float_var)  # Float: 9.12

# 3. String - sequence of characters enclosed in single (') or double (") quotation marks.

my_string_var = "antony"  #double quotes
my_str_var = 'antony'  #single quotes
print("String:", my_string_var)  # String: antony

# 4. Boolean - a true or false and they are written as .. True or False
my_boolean_var = True
print("Boolean:", my_boolean_var) #Boolean: True